"""Ejemplos de operadores y entrada/salida en Python."""

# Operadores aritméticos
a, b = 17, 5
print(f"Suma: {a + b}") # 22
print(f"Resta: {a - b}") # 12
print(f"Producto: {a * b}") # 85
print(f"División: {a / b}") # 3.4
print(f"División entera: {a // b}") # 3
print(f"Resto: {a % b}") # 2
print(f"Potencia: {a ** b}") # 1419857

# Operadores relacionales y lógicos
edad = 17
es_adolescente = 13 <= edad <= 17
print(f"¿Es adolescente? {es_adolescente}")

